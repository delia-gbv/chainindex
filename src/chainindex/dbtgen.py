"""Writes the dbt views that decode each chain's raw logs and calls on read, one per contract kind and event or read.

The SQL is generated from the chain files and ABIs and checked in; ``chainindex dbt --check`` fails when it is stale.
"""

import re
from pathlib import Path
from typing import Any

import yaml
from eth_abi.grammar import ABIType, TupleType, parse

from chainindex.abi import EventInput, EventSpec
from chainindex.config import ChainConfig, ContractSpec, FunctionSpec, ReadSpec

HEADER = "-- Generated by `chainindex dbt` from {source}. Do not edit: change the chain file or ABI and regenerate.\n"
COMMON_COLUMNS = (
    "chain_id", "address", "block_number", "block_time", "block_hash", "transaction_hash", "transaction_index",
    "log_index", "inserted_at",
)
INT_TYPE = re.compile(r"^(u?)int(\d*)$")
BYTES_TYPE = re.compile(r"^bytes(\d+)$")


def _word(index: int) -> str:
    """Returns the SQL for the 64 hex characters of data word ``index`` (``data`` keeps its ``0x``)."""
    return f"substring(data, {3 + 64 * index}, 64)"


def _topic_word(index: int) -> str:
    return f"substring(topic{index}, 3, 64)"


def _sized(kind: str, bits: int) -> str:
    """Returns the smallest ClickHouse integer type for an ABI integer width."""
    for size in (8, 16, 32, 64, 128, 256):
        if bits <= size:
            return f"{kind}{size}"
    raise ValueError(f"Integer wider than 256 bits: {bits}")


def static_value(abi_type: str, word: str) -> str | None:
    """Returns the SQL decoding one 32-byte word as ``abi_type``, or None for a type that is not one word."""
    if abi_type == "address":
        return f"concat('0x', substring({word}, 25, 40))"
    if abi_type == "bool":
        return f"toBool(reinterpretAsUInt256(reverse(unhex({word}))) != 0)"
    integer = INT_TYPE.match(abi_type)
    if integer:
        unsigned, bits_text = integer.groups()
        bits = int(bits_text or 256)
        raw = f"reinterpretAs{'UInt' if unsigned else 'Int'}256(reverse(unhex({word})))"
        target = _sized("UInt" if unsigned else "Int", bits)
        return raw if target.endswith("256") else f"to{target}({raw})"
    sized_bytes = BYTES_TYPE.match(abi_type)
    if sized_bytes:
        return f"concat('0x', substring({word}, 1, {2 * int(sized_bytes.group(1))}))"
    return None


def dynamic_value(abi_type: str, word: str) -> str | None:
    """Returns the SQL decoding a ``bytes`` or ``string`` value from its head word's offset, or None for others."""
    if abi_type not in ("bytes", "string"):
        return None
    start = f"(3 + 2 * reinterpretAsUInt64(reverse(unhex(substring({word}, 49, 16)))))"
    length = f"reinterpretAsUInt64(reverse(unhex(substring(data, {start} + 48, 16))))"
    content = f"substring(data, {start} + 64, 2 * {length})"
    return f"unhex({content})" if abi_type == "string" else f"concat('0x', {content})"


def head_words(abi_type: str) -> int:
    """Counts the 32-byte head words a non-indexed parameter takes (one for anything dynamic)."""
    return _head_words(parse(abi_type))


def _head_words(parsed: ABIType) -> int:
    if parsed.is_dynamic:
        return 1
    if parsed.arrlist:
        return parsed.arrlist[-1][0] * _head_words(parsed.item_type)
    if isinstance(parsed, TupleType):
        return sum(_head_words(component) for component in parsed.components)
    return 1


def column_name(item: EventInput) -> str:
    """Names a decoded column, renaming parameters that would shadow a log column."""
    return f"{item.column}_arg" if item.column in COMMON_COLUMNS else item.column


def event_columns(event: EventSpec) -> tuple[list[tuple[str, str, str]], list[str]]:
    """Returns ``(column, sql, abi_type)`` for each decodable parameter, and notes on the ones left out."""
    columns = []
    skipped = []
    topic = 1
    word = 0
    for item in event.inputs:
        name = column_name(item)
        if item.indexed:
            value = static_value(item.abi_type, _topic_word(topic)) if item.is_static else f"topic{topic}"
            columns.append((name, value or f"topic{topic}", item.abi_type))
            topic += 1
            continue
        value = static_value(item.abi_type, _word(word)) or dynamic_value(item.abi_type, _word(word))
        if value is None:
            skipped.append(f"{item.name} ({item.abi_type}) is not decoded in SQL; read it from `data`")
        else:
            columns.append((name, value, item.abi_type))
        word += head_words(item.abi_type)
    return columns, skipped


def model_name(chain: ChainConfig, contract: ContractSpec, event: EventSpec) -> str:
    """Names a decoded model (unique across the dbt project); its table is ``<contract>__<event>``."""
    return f"{chain.name}__{contract.name}__{event.table}"


def membership(chain: ChainConfig, contract: ContractSpec) -> str:
    """Returns the condition that keeps a decoded model to logs its kind's contracts emitted.

    Anyone can emit a log with a kind's topics. A created kind keeps an address only when a configured factory
    announced it, and a factory's own model keeps only logs its configured address emitted, which no one can forge.
    An ``any`` kind keeps every emitter: its consumers join the addresses they trust.
    """
    if contract.track == "any":
        return ""
    if contract.track != "created":
        return (
            f"  and address in (select address from {{{{ ref('{chain.name}__contracts') }}}} "
            f"where contract = '{contract.name}')\n"
        )
    created_by = []
    for factory in chain.factories_of(contract.name):
        creates = factory.creates
        if creates is None:
            continue
        event = next(spec for spec in factory.event_specs() if spec.name == creates.event)
        param = next(item for item in event.inputs if item.name == creates.param)
        created_by.append(f"select {column_name(param)} from {{{{ ref('{model_name(chain, factory, event)}') }}}}")
    return "  and address in (\n    " + "\n    union all ".join(created_by) + "\n  )\n"


def view_config(chain: ChainConfig, alias: str) -> str:
    """Returns the config block of a generated view: decoding happens on read, so nothing is stored twice."""
    return (
        "{{ config(\n"
        "    materialized='view',\n"
        f"    schema='{chain.decoded_schema}',\n"
        f"    alias='{alias}',\n"
        f"    tags=['chains', 'chain_{chain.name}'],\n"
        ") }}\n\n"
    )


def not_orphaned(chain: ChainConfig, indent: str) -> str:
    """Returns the condition that leaves out rows of blocks found off the canonical chain."""
    return (
        f"{indent}and (block_number, block_hash) not in (\n"
        f"{indent}  select block_number, block_hash from {{{{ source('chain_{chain.name}', 'orphaned_blocks') }}}}\n"
        f"{indent})\n"
    )


def log_model(chain: ChainConfig, contract: ContractSpec, alias: str, columns: list[str], topic_filter: str) -> str:
    """Returns a view over one kind's raw logs: the config, the log columns and ``columns``, and the filters."""
    select = [
        f"toUInt64({chain.chain_id}) as chain_id",
        "address",
        "block_number",
        "block_time",
        "block_hash",
        "transaction_hash",
        "transaction_index",
        "log_index",
        "inserted_at",
        *columns,
    ]
    return (
        view_config(chain, alias)
        + "select\n    " + ",\n    ".join(select) + "\n"
        + f"from {{{{ source('chain_{chain.name}', 'logs') }}}}\n"
        + f"where {topic_filter}\n"
        + membership(chain, contract)
        + not_orphaned(chain, "  ")
    )


def event_model(chain: ChainConfig, contract: ContractSpec, event: EventSpec) -> str:
    """Returns the SQL of one decoded event view."""
    columns, skipped = event_columns(event)
    lines = [HEADER.format(source=f"chains/{chain.name}.yaml and abis/{contract.abi}.json"), f"-- {event.signature}\n"]
    lines += [f"-- {note}\n" for note in skipped]
    decoded = [f"{sql} as {name}" for name, sql, _abi_type in columns]
    lines.append(log_model(chain, contract, f"{contract.name}__{event.table}", decoded, f"topic0 = '{event.topic0}'"))
    return "".join(lines)


def undecoded(contract: ContractSpec) -> bool:
    """Tells whether a kind stores logs without an ABI to decode them, so it gets a raw model."""
    return contract.abi is None and contract.events is None


def raw_model_name(chain: ChainConfig, contract: ContractSpec) -> str:
    """Names the undecoded model of a kind without an ABI; its table is ``<contract>__logs``."""
    return f"{chain.name}__{contract.name}__logs"


def raw_model(chain: ChainConfig, contract: ContractSpec) -> str:
    """Returns the SQL of every log a kind without an ABI emitted, undecoded."""
    return (
        HEADER.format(source=f"chains/{chain.name}.yaml")
        + "-- No ABI: every log of the kind's addresses, with its raw topics and data.\n"
        + log_model(chain, contract, f"{contract.name}__logs", ["topic0", "topic1", "topic2", "topic3", "data"], "true")
    )


def contracts_model(chain: ChainConfig) -> str:
    """Returns the SQL of the registry view: the latest row of every address."""
    return (
        HEADER.format(source=f"chains/{chain.name}.yaml")
        + view_config(chain, "contracts")
        + "select\n"
        "    address,\n"
        "    argMax(contract, inserted_at) as contract,\n"
        "    argMax(start_block, inserted_at) as start_block,\n"
        "    argMax(active, inserted_at) as active,\n"
        "    argMax(source, inserted_at) as source,\n"
        "    argMax(label, inserted_at) as label,\n"
        "    argMax(created_block, inserted_at) as created_block,\n"
        "    argMax(creation_args, inserted_at) as creation_args\n"
        f"from {{{{ source('chain_{chain.name}', 'contracts') }}}}\n"
        "group by address\n"
    )


def transactions_model(chain: ChainConfig) -> str:
    """Returns the SQL of the accounts' transactions on the canonical chain."""
    return (
        HEADER.format(source=f"chains/{chain.name}.yaml (accounts)")
        + view_config(chain, "transactions")
        + "-- Fees are in native wei: gas used at the effective price, plus the L1 data fee on OP-stack chains.\n"
        "select *\n"
        f"from {{{{ source('chain_{chain.name}', 'transactions') }}}}\n"
        "where (block_number, block_hash) not in (\n"
        f"    select block_number, block_hash from {{{{ source('chain_{chain.name}', 'orphaned_blocks') }}}}\n"
        ")\n"
    )


def event_transactions_model(chain: ChainConfig) -> str:
    """Returns the SQL of the transactions behind stored events, on the canonical chain."""
    return (
        HEADER.format(source=f"chains/{chain.name}.yaml (transactions)")
        + view_config(chain, "event_transactions")
        + "-- One row per transaction hash. gas_price is the effective price paid per gas, in native wei; the fee caps\n"
        "-- are null on a legacy transaction. Every transaction succeeded: a reverted one emits no log.\n"
        "select *\n"
        f"from {{{{ source('chain_{chain.name}', 'event_transactions') }}}}\n"
        "where (block_number, block_hash) not in (\n"
        f"    select block_number, block_hash from {{{{ source('chain_{chain.name}', 'orphaned_blocks') }}}}\n"
        ")\n"
    )


def event_transactions_model_name(chain: ChainConfig, contract: ContractSpec, event: EventSpec) -> str:
    """Names the view of one event joined to its transactions; its table is ``<contract>__<event>_transactions``."""
    return f"{model_name(chain, contract, event)}_transactions"


def event_with_transactions_model(chain: ChainConfig, contract: ContractSpec, event: EventSpec) -> str:
    """Returns the SQL of one decoded event beside the transaction that emitted it."""
    return (
        HEADER.format(source=f"chains/{chain.name}.yaml (transactions) and abis/{contract.abi}.json")
        + view_config(chain, f"{contract.name}__{event.table}_transactions")
        + f"-- Every {event.name} with its transaction's sender, recipient, nonce and fees; null until the transaction is\n"
        "-- stored (the event transactions lane trails the logs).\n"
        "select\n"
        "    event.*,\n"
        "    tx.sender as tx_sender,\n"
        "    tx.recipient as tx_recipient,\n"
        "    tx.nonce as tx_nonce,\n"
        "    tx.value as tx_value,\n"
        "    tx.type as tx_type,\n"
        "    tx.gas_limit as tx_gas_limit,\n"
        "    tx.gas_price as tx_gas_price,\n"
        "    tx.max_fee_per_gas as tx_max_fee_per_gas,\n"
        "    tx.max_priority_fee_per_gas as tx_max_priority_fee_per_gas,\n"
        "    tx.selector as tx_selector\n"
        f"from {{{{ ref('{model_name(chain, contract, event)}') }}}} as event\n"
        f"left join {{{{ ref('{chain.name}__event_transactions') }}}} as tx\n"
        "    on tx.transaction_hash = event.transaction_hash and tx.block_number = event.block_number\n"
    )


def transaction_kinds(chain: ChainConfig) -> list[tuple[ContractSpec, EventSpec]]:
    """Returns every ``(kind, event)`` whose transactions a chain file asks for."""
    return [
        (contract, event)
        for contract in chain.contracts if contract.transactions is not None
        for event in contract.event_specs() if event.name in contract.transactions.events
    ]


def sources_yaml(chain: ChainConfig) -> str:
    """Returns the sources file of one chain's raw database."""
    document = {
        "version": 2,
        "sources": [
            {
                "name": f"chain_{chain.name}",
                # A var moves the sources to another database, so a test can build from data of its own.
                "schema": f"{{{{ var('{chain.database}_database', '{chain.database}') }}}}",
                "description": f"Insert-only raw tables written by chainindex for {chain.name} (chain {chain.chain_id}).",
                "tables": [
                    {"name": "logs", "description": "Every kept log, confirmed, never updated, sorted by topic0 and address."},
                    {"name": "contracts", "description": "Registry changes; the latest row per address wins."},
                    {"name": "blocks", "description": "Headers of confirmed blocks seen live."},
                    {"name": "orphaned_blocks", "description": "Stored blocks found off the canonical chain."},
                    {"name": "audits", "description": "Every comparison of stored logs with the RPC."},
                    {"name": "calls", "description": "Raw view-call results of the reads, a row only when a result changed."},
                    {"name": "transactions", "description": "The accounts' transactions with their receipts and fees."},
                    {
                        "name": "event_transactions",
                        "description": "The transactions behind the stored events of the kinds that ask for them, raw, one per hash.",
                    },
                ],
            }
        ],
    }
    return HEADER.format(source=f"chains/{chain.name}.yaml").replace("-- ", "# ", 1) + yaml.safe_dump(document, sort_keys=False)


def read_model_name(chain: ChainConfig, read: ReadSpec) -> str:
    """Names a decoded read model; its table is ``read__<read>``."""
    return f"{chain.name}__read__{read.name}"


def _output_value(abi_type: str, index: int, column: str, condition: str = "") -> str:
    """Returns the SQL decoding output word ``index`` of the return data in ``column``, NULL when it is too short or
    ``condition`` fails."""
    value = static_value(abi_type, f"substring({column}, {3 + 64 * index}, 64)")
    if value is None:
        raise ValueError(f"Reads decode one-word outputs only, not {abi_type}")
    return f"if({condition}length({column}) >= {2 + 64 * (index + 1)}, toNullable({value}), NULL)"


def read_columns(read: ReadSpec) -> list[tuple[str, str]]:
    """Returns ``(column, abi_type)`` of a read model's decoded columns."""
    if read.tick_map is not None:
        return [("tick", "int24"), *((column, abi_type) for abi_type, column in FunctionSpec.parse(read.tick_map.ticks).outputs)]
    return [(column, abi_type) for function in read.functions() for abi_type, column in function.outputs]


def read_model(chain: ChainConfig, read: ReadSpec) -> str:
    """Returns the SQL of one read: a row per tick that changed, or per block and address where a call changed.

    ``calls`` holds a result only when it changed, so a value holds from its row until the next one.
    """
    calls = f"{{{{ source('chain_{chain.name}', 'calls') }}}}"
    lines = [HEADER.format(source=f"chains/{chain.name}.yaml (reads.{read.name})"), view_config(chain, f"read__{read.name}")]
    if read.tick_map is not None:
        ticks = FunctionSpec.parse(read.tick_map.ticks)
        lines.append(
            "-- A row per tick whose result changed; NULLs mean the call failed, and no gross liquidity means the tick\n"
            "-- was cleared. Only ticks near the price are read, so a tick's last row can predate its leaving that window.\n"
        )
        select = [
            f"toUInt64({chain.chain_id}) as chain_id", "block_number", "block_hash", "block_time", "address",
            "toInt32(reinterpretAsInt256(reverse(unhex(substring(input, 11, 64))))) as tick",
            *(
                f"{_output_value(abi_type, index, 'output', 'success and ')} as {column}"
                for index, (abi_type, column) in enumerate(ticks.outputs)
            ),
            "inserted_at",
        ]
        lines.append("select\n    " + ",\n    ".join(select) + "\n")
        lines.append(f"from {calls}\nwhere read = '{read.name}' and function = '{ticks.name}'\n" + not_orphaned(chain, "  "))
        return "".join(lines)
    lines.append(
        "-- A row per block where any call of an address changed; a call that did not change there, or failed, is NULL.\n"
        "-- A value holds from its row until the next non-NULL one.\n"
    )
    select = [f"toUInt64({chain.chain_id}) as chain_id", "block_number", "block_hash", "any(block_time) as block_time", "address"]
    select += [
        f"anyIf({_output_value(abi_type, index, 'output', 'success and ')}, function = '{function.name}') as {column}"
        for function in read.functions()
        for index, (abi_type, column) in enumerate(function.outputs)
    ]
    select.append("max(inserted_at) as inserted_at")
    lines.append("select\n    " + ",\n    ".join(select) + "\n")
    lines.append(f"from {calls}\nwhere read = '{read.name}'\n" + not_orphaned(chain, "  "))
    lines.append("group by block_number, block_hash, address\n")
    return "".join(lines)


def models_yaml(chain: ChainConfig) -> str:
    """Returns the schema file documenting every decoded model's columns."""
    models: list[dict[str, Any]] = [
        {
            "name": f"{chain.name}__contracts",
            "description": "Every address chainindex indexes or indexed, with its contract kind.",
        }
    ]
    for contract in chain.contracts:
        for event in contract.event_specs():
            columns, _skipped = event_columns(event)
            models.append(
                {
                    "name": model_name(chain, contract, event),
                    "description": f"{contract.name}.{event.signature} logs, decoded from chain_{chain.name}.logs.",
                    "columns": [
                        {"name": name, "description": f"{abi_type}"} for name, _sql, abi_type in columns
                    ],
                }
            )
        if undecoded(contract):
            models.append(
                {
                    "name": raw_model_name(chain, contract),
                    "description": f"Every log of {contract.name}'s addresses, undecoded: it has no ABI.",
                }
            )
    for read in chain.reads:
        models.append(
            {
                "name": read_model_name(chain, read),
                "description": (
                    f"State read {read.name} of every {read.contract} every {read.every_blocks} block(s), "
                    "a row where it changed."
                ),
                "columns": [{"name": name, "description": abi_type} for name, abi_type in read_columns(read)],
            }
        )
    if transaction_kinds(chain):
        models.append(
            {
                "name": f"{chain.name}__event_transactions",
                "description": "The transactions behind stored events, one per hash, with the sender's fees typed.",
                "data_tests": [{"unique_grain": {"arguments": {"columns": ["transaction_hash"]}}}],
                "columns": [
                    {"name": "transaction_hash", "data_tests": ["not_null"]},
                    {"name": "sender", "description": "The account that signed and paid for the transaction.", "data_tests": ["not_null"]},
                    {"name": "recipient", "description": "The contract called: a router, an aggregator or the pool itself."},
                    {"name": "gas_price", "description": "The effective price paid per gas, in native wei.", "data_tests": ["not_null"]},
                    {"name": "max_priority_fee_per_gas", "description": "The tip the sender offered per gas; null on a legacy transaction."},
                    {"name": "selector", "description": "The first four bytes of the calldata: the method called."},
                ],
            }
        )
    # No grain test on the joined views: the transactions' own test keeps one row per hash, so the join adds no rows,
    # and testing the view hashed every stored transaction and scanned every swap, past dbt's 3 GiB and the lane's deadline.
    for contract, event in transaction_kinds(chain):
        models.append(
            {
                "name": event_transactions_model_name(chain, contract, event),
                "description": f"Every {contract.name}.{event.name} beside its transaction's sender, recipient and fees (tx_ columns).",
            }
        )
    document = {"version": 2, "models": models}
    return HEADER.format(source=f"chains/{chain.name}.yaml").replace("-- ", "# ", 1) + yaml.safe_dump(document, sort_keys=False)


def render(chain: ChainConfig) -> dict[str, str]:
    """Returns every generated file of one chain, keyed by its name inside ``models/chains/<chain>/``."""
    files = {
        f"_{chain.name}__sources.yml": sources_yaml(chain),
        f"_{chain.name}__models.yml": models_yaml(chain),
        f"{chain.name}__contracts.sql": contracts_model(chain),
    }
    for contract in chain.contracts:
        for event in contract.event_specs():
            files[f"{model_name(chain, contract, event)}.sql"] = event_model(chain, contract, event)
        if undecoded(contract):
            files[f"{raw_model_name(chain, contract)}.sql"] = raw_model(chain, contract)
    for read in chain.reads:
        files[f"{read_model_name(chain, read)}.sql"] = read_model(chain, read)
    if chain.accounts:
        files[f"{chain.name}__transactions.sql"] = transactions_model(chain)
    if transaction_kinds(chain):
        files[f"{chain.name}__event_transactions.sql"] = event_transactions_model(chain)
    for contract, event in transaction_kinds(chain):
        files[f"{event_transactions_model_name(chain, contract, event)}.sql"] = event_with_transactions_model(chain, contract, event)
    return files


def write(chains: list[ChainConfig], models_dir: Path) -> list[Path]:
    """Writes every chain's files, removes stale ones, and returns the paths that changed."""
    changed = []
    for chain in chains:
        folder = models_dir / "chains" / chain.name
        folder.mkdir(parents=True, exist_ok=True)
        files = render(chain)
        for name, content in files.items():
            path = folder / name
            if not path.exists() or path.read_text() != content:
                path.write_text(content)
                changed.append(path)
        for path in folder.iterdir():
            if path.name not in files:
                path.unlink()
                changed.append(path)
    return changed


def stale(chains: list[ChainConfig], models_dir: Path) -> list[str]:
    """Lists generated files that are missing, different or left over."""
    problems = []
    for chain in chains:
        folder = models_dir / "chains" / chain.name
        files = render(chain)
        for name, content in files.items():
            path = folder / name
            if not path.exists() or path.read_text() != content:
                problems.append(str(path))
        if folder.exists():
            problems.extend(str(path) for path in folder.iterdir() if path.name not in files)
    return problems
